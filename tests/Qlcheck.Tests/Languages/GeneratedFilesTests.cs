namespace Qlcheck.Tests;

public class GeneratedFilesTests
{
    [Theory]
    [InlineData("src/Api.g.cs", "", true)]
    [InlineData("src/Api.g.i.cs", "", true)]
    [InlineData("src/Form1.Designer.cs", "", true)]
    [InlineData("src/Client.generated.cs", "", true)]
    [InlineData("src/Client.cs", "// <auto-generated>\n// This code was generated by a tool.\n", true)]
    [InlineData("src/Client.cs", "namespace A;\n\n\n\n\n\n// <auto-generated> later in the file\n", false)]
    [InlineData("src/Client.cs", "namespace A;\n", false)]
    public void Generated_files_are_known_by_name_or_header(string path, string text, bool generated)
    {
        Assert.Equal(generated, GeneratedFiles.IsGenerated(path, text));
    }
}
